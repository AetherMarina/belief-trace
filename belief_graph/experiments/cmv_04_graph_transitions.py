import pandas as pd
import networkx as nx
from pyvis.network import Network


class LongitudinalGraphEngine:
    def __init__(self):
        # Directed graph to represent inference/implication paths
        self.graph = nx.DiGraph()

    def load_initial_t1_state(self, thread_id, op_id, triplets):
        """Builds the initial belief system state at T1."""
        for subject, relation, obj in triplets:
            self.graph.add_edge(
                subject,
                obj,
                relation=relation,
                status="active",
                temporal_step=1,
                thread_id=thread_id,
                author=op_id
            )
        print(f"[GraphEngine] T1 state initialized for Thread {thread_id} with {self.graph.number_of_edges()} edges.")

    def transition_to_t2_state(self, deprecated_triplets, new_triplets, processing_time):
        """Updates graph state to T2, deprecating broken edges and adding new context."""
        # 1. Deprecate beliefs that were changed
        for u, _, v in deprecated_triplets:
            if self.graph.has_edge(u, v):
                self.graph[u][v]["status"] = "deprecated"
                self.graph[u][v]["deprecated_at_step"] = 2
                self.graph[u][v]["processing_overhead_minutes"] = processing_time
                print(f"[GraphEngine] Deprecated edge due to cognitive shift: {u} -> {v}")
            else:
                print(f"[GraphEngine] Warning: Edge {u} -> {v} not found to deprecate.")

        # 2. Add new contextual constraints emerged at T2
        for subject, relation, obj in new_triplets:
            self.graph.add_edge(
                subject,
                obj,
                relation=relation,
                status="active",
                temporal_step=2
            )
            print(f"[GraphEngine] Added updated T2 edge: {subject} --({relation})--> {obj}")


def main():
    # Load the CSV generated by the previous script
    csv_file = "data/cmv_longitudinal_dataset.csv"
    print(f"Reading dataset from {csv_file}...")
    df = pd.read_csv(csv_file)

    if df.empty:
        print("Error: The dataset is empty.")
        return

    # Process Row 0 (The Nature vs Man-made discussion)
    row_0 = df.iloc[0]

    thread_id = row_0["Thread_ID"]
    op_id = row_0["OP_User_ID"]
    processing_time = row_0["Processing_Time_Minutes"]

    print(f"\nProcessing Thread: {thread_id} | OP: {op_id}")
    print(f"Cognitive Processing Delay to reach Delta: {processing_time:.2f} minutes")

    # Initialize Engine
    engine = LongitudinalGraphEngine()

    # --- SIMULATED TRIPLET INJECTION (To be fully automated by LLM/NLP in Phase 2) ---
    # Core belief structures extracted from row_0["T1_Original_Belief"]
    t1_triplets = [
        ("Humans", "PART_OF", "Nature"),
        ("Man-made Things", "CREATED_BY", "Humans"),
        ("Man-made Things", "MUST_BE", "Natural"),
    ]

    # Load T1
    engine.load_initial_t1_state(thread_id, op_id, t1_triplets)

    print("\n--- Executing T2 Transition ---")
    # State change based on row_0["Catalyst_Argument"] and row_0["T2_Actual_Explanation"]
    edges_to_deprecate = [("Man-made Things", "MUST_BE", "Natural")]

    t2_new_triplets = [
        ("Definition of Natural", "DEPENDS_ON", "Context"),
        ("Man-made Things", "EXCLUDED_FROM_NATURAL_IN", "Practical Context"),
    ]

    # Process longitudinal update
    engine.transition_to_t2_state(edges_to_deprecate, t2_new_triplets, processing_time)

    # --- VERIFY FINAL GRAPH ENTITIES AND METADATA ---
    print("\n--- Final NetworkX Internal Graph State ---")
    for u, v, data in engine.graph.edges(data=True):
        print(f"Edge: ({u} -> {v})")
        print(f"  Metadata: {data}")

    visualize_graph_interactively(engine.graph)


def visualize_graph_interactively(nx_graph):
    # Create an interactive network
    net = Network(height="750px", width="100%", bgcolor="#222222", font_color="white", directed=True)

    # Add nodes and edges from our NetworkX graph
    for u, v, data in nx_graph.edges(data=True):
        # Color edges based on their status
        if data['status'] == 'deprecated':
            edge_color = "#ff4d4d"  # Red for old/deprecated beliefs
            edge_width = 1
            edge_label = f"(DEPRECATED)\n{data['relation']}"
        else:
            edge_color = "#00cc66"  # Green for new/active beliefs
            edge_width = 3
            edge_label = data['relation']

        net.add_node(u, label=u, color="#4da6ff", shape="box")
        net.add_node(v, label=v, color="#4da6ff", shape="box")

        net.add_edge(u, v, color=edge_color, width=edge_width, title=str(data), label=edge_label)

    # Save as an HTML file
    file_name = "data/longitudinal_belief_graph.html"
    net.write_html(file_name)
    print(f"Graph saved! Open {file_name} in your browser.")


if __name__ == "__main__":
    main()
